// Run after changing a preloaded asset; --check verifies the committed manifest.
import {readFile,stat,writeFile} from 'node:fs/promises';
import {aircraftFiles} from '../src/preload.js';

const variants=[['b747',{}],['a380',{}],['a330',{}],['shuttle',{}],['b777',{livery:'BOE'}],['b777',{livery:'fedex'}]];
const paths=[...new Set(variants.flatMap(([type,options])=>aircraftFiles(type,options).map(([path])=>path)))].sort();
const sizes=Object.fromEntries(await Promise.all(paths.map(async path=>[path,(await stat(new URL('../assets/'+path,import.meta.url))).size])));
const output='// Generated by tools/generate-aircraft-download-sizes.mjs. Uncompressed bytes.\nexport const AIRCRAFT_DOWNLOAD_SIZES='+JSON.stringify(sizes,null,1)+';\n';
const file=new URL('../src/aircraft-download-sizes.js',import.meta.url);
if(process.argv.includes('--check')){
 if(await readFile(file,'utf8')!==output)throw Error('Aircraft download sizes are stale; run node tools/generate-aircraft-download-sizes.mjs');
 console.log('Aircraft download sizes match assets.');
}else await writeFile(file,output);
